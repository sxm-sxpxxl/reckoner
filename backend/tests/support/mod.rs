//! Подключение к тестовой базе. Каждый тест работает в транзакции, которая
//! откатывается при выходе, поэтому тесты не видят друг друга и не оставляют
//! мусора — чистить ничего не нужно.

use std::time::Duration;

use sqlx::{PgPool, postgres::PgPoolOptions};

/// Пул к бранчу `test`. Отдельная переменная, а не `DATABASE_URL`: тесты пишут
/// и удаляют данные, и перепутать их базу с рабочей нельзя.
///
/// Паникует, если переменная не задана. Тихо проходить такой тест не должен —
/// зелёный прогон без базы создаёт ложное чувство покрытия.
///
/// Пул поднимается на каждый тест, и общего на бинарник тут быть не может:
/// каждый `#[tokio::test]` запускает собственный рантайм, а соединения живут
/// в том рантайме, где созданы. Статический пул переживал первый тест и падал
/// в остальных с `A Tokio 1.x context was found, but it is being shutdown`.
/// Поэтому ограничивается не число пулов, а число соединений в каждом — см.
/// `max_connections` ниже.
pub async fn test_pool() -> PgPool {
    // `cargo test` не читает `.env` сам, в отличие от бинарника, который делает
    // это в `main`. Без этой строки переменная не найдётся, даже если она в файле.
    // Уже заданные в окружении значения `dotenvy` не перетирает.
    dotenvy::dotenv().ok();

    let url = std::env::var("TEST_DATABASE_URL").expect(
        "TEST_DATABASE_URL не задана. Интеграционные тесты требуют бранч `test` в Neon; \
         строка подключения кладётся в backend/.env (см. docs/setup-neon.md). \
         В CI эти тесты не запускаются: там идёт только `cargo test --lib`.",
    );

    // Два соединения, а не пять, как у сервера. Тестов десятки, харнесс гоняет
    // их параллельно по числу ядер, и пул у каждого свой — при пяти пиковое
    // число подключений к одному compute Neon упиралось в его лимит, и тесты
    // начинали падать вразнобой: `peer closed connection without sending TLS
    // close_notify`, без всякой связи с проверяемой логикой.
    //
    // Тесту хватает одного: он открывает единственную транзакцию и работает
    // только ей. Второе — запас на случай, если ручка внутри себя возьмёт ещё
    // одно соединение.
    //
    // Таймаут щедрый и это не перестраховка: спящий compute Neon просыпается
    // секунды, и под несколькими подключениями разом первое соединение
    // случалось дольше десяти секунд. С десятисекундным таймаутом прогон падал
    // на `PoolTimedOut` в самом `connect` — то есть проверка ломалась там, где
    // база всего лишь медленно отвечала.
    let pool = PgPoolOptions::new()
        .max_connections(2)
        .acquire_timeout(Duration::from_secs(60))
        .connect(&url)
        .await
        .expect("не удалось подключиться к тестовой базе");

    backend::db::run_migrations(&pool)
        .await
        .expect("не удалось применить миграции к тестовой базе");

    pool
}
