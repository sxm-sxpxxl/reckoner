/**
 * Заглушки обложек: тёмный фон и пятно света снизу за эмодзи.
 *
 * Тона строгие и десатурированные — gunmetal, слэйт, оливковый, графит.
 * Светлые градиенты из хендоффа заменены осознанно: приложение называется
 * «Финальная расплата», и карточки в сетке должны читаться как афиши, а не как
 * пастельные плитки.
 *
 * Свет приглушён специально. Насыщенное оранжевое пятно спорило бы с бейджем
 * статуса, который на обложке и так лежит поверх, — а статус тут важнее.
 */
const SPOTLIGHTS = [
  // Gunmetal: холодная сталь.
  'radial-gradient(120% 130% at 50% 118%, rgba(150,170,190,.30) 0%, rgba(150,170,190,0) 58%), linear-gradient(168deg,#23262A 0%,#0C0D0F 100%)',
  // Графит с тёплым, но сдержанным светом — единственный тёплый из четырёх.
  'radial-gradient(120% 130% at 50% 118%, rgba(224,140,60,.26) 0%, rgba(224,140,60,0) 58%), linear-gradient(168deg,#26241F 0%,#0D0C0A 100%)',
  // Слэйт: ночной синий.
  'radial-gradient(120% 130% at 50% 118%, rgba(120,150,190,.28) 0%, rgba(120,150,190,0) 58%), linear-gradient(168deg,#1E2530 0%,#090C11 100%)',
  // Olive drab: армейский.
  'radial-gradient(120% 130% at 50% 118%, rgba(160,175,130,.24) 0%, rgba(160,175,130,0) 58%), linear-gradient(168deg,#232520 0%,#0B0C09 100%)',
]

/**
 * Обложка по идентификатору встречи.
 *
 * Хендофф предлагает брать индекс карточки в списке, но тогда при смене
 * сортировки у встречи меняется картинка — список моргает, и обложка перестаёт
 * быть приметой встречи. Хеш от `id` даёт стабильный вид на всю её жизнь.
 */
export function coverGradient(id: string): string {
  let hash = 0

  for (let index = 0; index < id.length; index += 1) {
    hash = (hash * 31 + id.charCodeAt(index)) >>> 0
  }

  return SPOTLIGHTS[hash % SPOTLIGHTS.length]
}
