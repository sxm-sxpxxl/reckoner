/**
 * Несколько случайных фраз без повторов.
 *
 * Перемешиваем копию, а не исходный массив: он экспортирован, и менять его
 * на месте значило бы менять его у всех, кто им пользуется.
 */
export function pickPhrases(count: number): string[] {
  const pool = [...PHRASES]

  for (let index = pool.length - 1; index > 0; index -= 1) {
    const swap = Math.floor(Math.random() * (index + 1))

    ;[pool[index], pool[swap]] = [pool[swap], pool[index]]
  }

  return pool.slice(0, Math.min(count, pool.length))
}
